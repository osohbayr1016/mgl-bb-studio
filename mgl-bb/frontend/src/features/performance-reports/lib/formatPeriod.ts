/* =============================================================
 * Тайлангийн хугацааны мужийг эвлүүлэх ГАНЦ эх сурвалж.
 * -------------------------------------------------------------
 * Хэрэглэгч `period_start` эсвэл `period_end`-ийн аль нэгийг нь
 * хоосон үлдээвэл урьдчилан харах/жагсаалт дээр «–2026-07-22»
 * гэсэн толгойгүй зураас гарч байсан.  Аль нэг тал нь хоосон бол
 * холбогч зураас ОГТ гарахгүй — байгаа огноо ганцаараа харагдана.
 * Хоёулаа хоосон бол хоосон мөр буцаана (дуудагч тэр мөрөө бүхэлд
 * нь render хийхгүй байх ёстой).
 * ============================================================= */

/** Хугацааны мужийг эвлүүлнэ.  Аль нэг тал нь хоосон бол холбогч
 *  зураас ГАРАХГҮЙ — «–2026-07-22» гэж харагдахаас сэргийлнэ. */
export function formatPeriodRange(
  start: string | null | undefined,
  end: string | null | undefined,
  sep = ' – ',
): string {
  const a = (start ?? '').trim();
  const b = (end ?? '').trim();
  if (a && b) return `${a}${sep}${b}`;
  return a || b || '';
}

/** Муж огт байхгүй эсэх — «Хугацаа:» гэх мэт шошго дангаараа
 *  үлдэхээс сэргийлж мөрийг бүхэлд нь алгасахад хэрэглэнэ. */
export function hasPeriodRange(
  start: string | null | undefined,
  end: string | null | undefined,
): boolean {
  return formatPeriodRange(start, end) !== '';
}
