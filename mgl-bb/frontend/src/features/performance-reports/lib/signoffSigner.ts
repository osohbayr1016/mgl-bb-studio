/** Баталгаажуулалт хуудасны зүүн (Гүйцэтгэгч) баганын «Төлөөлөгчийн
 *  нэр, албан тушаал» талбарын түлхүүр.  Редакторын «Боловсруулсан
 *  ажилтан» input мөн ЯГ ЭНЭ түлхүүрт бичнэ. */
export const SIGNOFF_EXEC_REP_KEY = 'signoff.exec.val.rep';

/** «Боловсруулсан ажилтан» талбарт бичсэн нэрээр хэрэглэгчийг олно.
 *  Үнийн саналын зан төлөвтэй ижил: нэр бичихэд тухайн хүний гарын
 *  үсэг доор нь гарч ирнэ.  Таарахгүй бол зураг байхгүй — талбар
 *  хоосон үлдэнэ (алдаа БИШ). */
export function findSigner(users: User[], typed: string): User | null {
  const q = typed.trim().toLowerCase();
  if (!q) return null;
  return (
    users.find((u) => {
      const n = (u.full_name || '').trim().toLowerCase();
      if (!n) return false;
      // Бүтэн таарах · бичиж дуусаагүй байхад угтвараар · товчилсон
      // нэр бичсэн үед эсрэгээр нь.
      return n === q || n.startsWith(q) || q.startsWith(n);
    }) ?? null
  );
}

/** Гарын үсгийн зургийн БҮТЭН зам (эсвэл null).
 *
 *  ⚠️ `signature_url` нь «shared/types»-ийн «User» интерфэйст
 *  ЗАРЛАГДААГҮЙ (тэр файл өөр эзэмшилтэй) тул structural cast-аар
 *  уншина — «ProfilePage.tsx» / «QuotePrintPage.tsx»-тай ижил хэв маяг.
 *  Backend «GET /api/users» нь USER_SELECT дотор энэ баганыг буцаана
 *  (routes/users.ts).
 *
 *  Нөхөлт (fallback) ЗОРИУДААР БАЙХГҮЙ — өөр хүний гарын үсгийг
 *  хэзээ ч орлуулж болохгүй. */
export function signerSignatureUrl(user: User | null): string | null {
  if (!user) return null;
  const raw = (user as { signature_url?: string | null }).signature_url ?? null;
  return raw ? mediaUrl(raw) : null;
}

/** «Боловсруулсан ажилтан»-ы ХҮЧИН ТӨГӨЛДӨР нэр.
 *
 *  Дараалал: хэрэглэгчийн бичсэн override → тайланг ҮҮСГЭСЭН хүний нэр.
 *
 *  Яагаад авто-нөхөлт хэрэгтэй вэ: түлхүүр нь ХООСОН байхад гарын үсэг
 *  огт гардаггүй байсан бөгөөд тэр талбарыг бөглөх ёстойг хэн ч мэдэхгүй
 *  (тайлан 48-ын блокийн `content_json` production дээр яг `{}` байв).
 *  Ингэснээр «нээгээд шууд гарын үсэгтэй» болно, гэхдээ override нь
 *  ҮРГЭЛЖ давамгайлах тул гараар өөр хүн бичих боломж хэвээр.
 *
 *  ⚠️ ХООСОН МӨР ('') нь «хэрэглэгч зориуд арилгасан» гэсэн утгатай тул
 *  авто-нэр рүү БУЦАХГҮЙ — `ReportTextContext.t`-ийн семантиктай ижил
 *  (`undefined` = авто, '' = хүний утга). */
export function resolveSignerName(
  override: string | undefined,
  users: User[],
  createdById: number | null | undefined,
): string {
  if (typeof override === 'string') return override;
  if (createdById == null) return '';
  return users.find((u) => u.id === createdById)?.full_name ?? '';
}
