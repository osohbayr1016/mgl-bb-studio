/**
 * Мянгатыг НАРИЙХАН ЗАЙГААР тусгаарлана (U+2009).  `toLocaleString('mn-MN')`
 * таслал тавьдаг нь техникийн зургийн хэвд харш, мөн 3-5м-ээс таслал цэгтэй
 * андуурагддаг.  Зай нь тодорхой бүлэглэдэг.
 */
export function tvNumber(value: number): string {
  if (!Number.isFinite(value)) return '—';
  const rounded = Math.round(value);
  return rounded.toLocaleString('en-US').replace(/,/g, ' ');
}

/** Явцын хувь — TV-д зориулсан өнгөний шат (нэг гэр бүл, солонго биш). */
export function tvProgressColor(v: number): string {
  if (v >= 100) return TV.up;
  if (v >= 75) return '#5BC9AE';
  if (v >= 40) return TV.accent;
  if (v >= 10) return TV.warn;
  return TV.ink3;
}
