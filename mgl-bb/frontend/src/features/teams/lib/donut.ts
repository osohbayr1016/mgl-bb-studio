import type { PersonDayWork } from './currentWork';

export interface DonutSlice {
  key: string | number;
  label: string;
  value: number;
  color: string;
  /** Богино код (BA, HAS) — домогт нэрийн ӨМНӨ моно үсгээр гарна. */
  code?: string;
  /** Hover дээр гарах нэмэлт тайлбар (заавал биш). */
  hint?: string;
  /** Бүдэг зүсэм («төсөлгүй») — дүүргэлт 40% тунгалаг, домгийн дөрвөлжин ч мөн. */
  muted?: boolean;
  /**
   * Hover дээр гарах НЭРСИЙН жагсаалт (2026-09-15, эзний хүсэлт: «зүсэм дээр
   * хулганаа аваачихад тэр баг/төсөл дээр ажиллаж буй БҮХ ажилтны нэр
   * харагдаг байх»).  Бүлэглэсэн — баг бол төслөөр, төсөл бол багаар.
   * Байхгүй бол зөвхөн энгийн tooltip.
   */
  roster?: RosterGroup[];
  /** Толгойн «нээх» холбоос (багийн / төслийн хуудас). */
  href?: string;
}

/** Нэрсийн нэг бүлэг — өнгө нь бүлгийн (төслийн эсвэл багийн) өнгө. */
export interface RosterGroup {
  key: string | number;
  label: string;
  code?: string;
  color: string;
  muted?: boolean;
  /** Толгойгүй хавтгай жагсаалт (Тоймын багийн самбар — 2026-09-16). */
  hideHeader?: boolean;
  people: RosterPerson[];
}

export interface RosterPerson {
  user_id: number;
  full_name: string;
  /** «Тэлмэн .Б» — жагсаалтад ХАРУУЛДАГ нэр (`shortPersonName`); бүтэн нэр `title`-д. */
  display_name: string;
  /**
   * Нэрийн ДООР жижиг мөр — бүтэцтэй (2026-09-16, эзний хүсэлт: «нэр ТОД,
   * доор нь жижгээр: хамгийн том төсөл, бусад төслүүд»).
   * `primary` = үндсэн төсөл, `others` = бусад төслийн нэрс.
   */
  /** `repair` = засварын (дотоод) төсөл (0324) — нэрийн хажууд «Засвар» шошго.
   *  `duration` = тэр засварын төсөл дээр өнөөдөр бүртгэсэн цаг («2 цаг 30 мин») —
   *  ижил төсөл тусдаа мөр болж ДАВХАР харагдахгүйн тулд энд нийлнэ. */
  primary?: { id: number; label: string; color: string; repair?: boolean; duration?: string };
  others?: RosterProjectLabel[];
  /** Ирцийн хэмжүүр: өдрийн ӨМНӨХ шатанд л сонгосон төслүүд («өмнө нь: …»). */
  earlier?: RosterProjectLabel[];
  /** Ирцийн хэмжүүр, мужаар: үндсэн төсөл дээр суусан өдрийн тоо («12 өдөр»). */
  days?: string;
  /** Бүтэцтэй талбар байхгүй үеийн (төсөлгүй хүн) жижиг мөр + `title`-ийн бичвэр. */
  note?: string;
  /** Энэ хүний ҮНДСЭН төсөл өөр (нүдний самбарт) — бүдэг харуулна. */
  elsewhere?: boolean;
  /** Ирцийн хэмжүүр: ОДОО (ирцээ хаагаагүй) `primary` төсөл дээр сууж байна. */
  now?: boolean;
  /** Ирцийн хэмжүүр: өнөөдөр ирцээ хаасан — `primary` нь сүүлд ажилласан төсөл. */
  left?: boolean;
  /** Төсөлгүй хүн — нэр бүдэг. */
  muted?: boolean;
  /**
   * «Одоогийн ажил» (2026-09-24): сонгосон өдрийн төслийн бус ажил + засварын
   * цаг (`lib/currentWork.ts`).  Зөвхөн ажилтай хүнд, «Өдөр» мужид.
   */
  work?: PersonDayWork;
}

/** Бусад / өмнөх төслийн шошго — засварын төслийг ялгана. */
export interface RosterProjectLabel {
  label: string;
  repair?: boolean;
}

/** «Төсөлгүй» зүсмийн өнгө — текстийн саарал, `muted: true`-тэй хамт 40%
 *  тунгалагаар зурагдана.  `--color-muted` (дэвсгэрийн саарал) харанхуй
 *  сэдэвт картаас ялгарахгүй байсан. */
export const IDLE_COLOR = 'var(--color-muted-foreground)';
export const MUTED_OPACITY = 0.4;
