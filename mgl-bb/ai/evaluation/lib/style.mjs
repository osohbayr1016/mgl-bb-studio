const LATIN_SENTENCE = /(?:^|[.!?:]\s+)([A-Z][a-z]+(?:\s+[a-z]+){3,})/u;


const normWords = (x) => x.toLowerCase().replace(/[^\p{L}\p{N} ]+/gu, ' ').replace(/\s+/g, ' ').trim();

/** Нэг мөр/өгүүлбэр доторх таслалын жагсаалт: ≥5 зүйл, ихэнх нь богино (≤3 үг, тоогүй), дундаас нь ижил зүйл ДАХИН гарсан. */
function listLoop(text) {
  for (const sent of text.split(/(?<=[.!?])\s+|\n+/u)) {
    const items = sent.split(/,\s*/u).map(normWords).filter((x) => x.length > 0);
    if (items.length < 5) continue;
    const short = items.filter((x) => x.split(' ').length <= 3 && !/\d/.test(x));
    if (short.length / items.length < 0.7) continue;
    const seen = new Set();
    let dup = 0;
    for (const it of short) {
      if (seen.has(it)) dup += 1;
      else seen.add(it);
    }
    if (dup >= 2) return true;
  }
  return false;
}

/** Нэг богино өгүүлбэрт (≤30 үг) ≥4 үсэгтэй нэг үг ≥4 удаа — «төрөл, параметр, төрөл холбоог, төрөл төлөв, төрөл төлөвийн …». */
const WORD_STOP = new Set(['байна', 'болон', 'байх', 'бөгөөд', 'байдаг', 'хэрэв', 'нэмэлт', 'тухайн', 'хамгийн', 'хоёр', 'гурав', 'зөвхөн']);
function wordLoop(text) {
  for (const sent of text.split(/(?<=[.!?])\s+|\n+/u)) {
    const w = normWords(sent).split(' ').filter(Boolean);
    if (w.length < 8 || w.length > 30) continue;
    const c = new Map();
    for (const x of w) if (x.length >= 4 && !WORD_STOP.has(x)) c.set(x, (c.get(x) ?? 0) + 1);
    for (const n of c.values()) if (n >= 4 && n / w.length >= 0.22) return true;
  }
  return false;
}

/** ИЖИЛ өгүүлбэр (≥4 үг) ХОЁР УДАА ЗЭРГЭЛДЭЭ (өгүүлбэр/блок). */
function repeatedSentence(text) {
  const sents = text.split(/(?<=[.!?])\s+/u).map(normWords).filter((x) => x.length > 0);
  for (let i = 1; i < sents.length; i++) {
    if (sents[i].split(' ').length >= 4 && sents[i] === sents[i - 1]) return true;
    if (i >= 2 && sents[i].split(' ').length >= 4 && sents[i] === sents[i - 2] && sents[i - 1] === sents[i - 3]) return true;
  }
  // «A. B. A. B.» блок
  for (let i = 3; i < sents.length; i++) if (sents[i] === sents[i - 2] && sents[i - 1] === sents[i - 3] && sents[i].split(' ').length >= 3) return true;
  return false;
}

export function styleLint(text, lang = 'mn-Cyrl') {
  const hits = {};
  let total = 0;
  for (const [k, res] of Object.entries(PATTERNS)) {
    const n = res.reduce((a, re) => a + (re.test(text) ? 1 : 0), 0);
    hits[k] = n;
    total += n;
  }
  // ФУНКЦЭЭР шалгах гогцоонууд (regex нь хүснэгт/жагсаалтын хууль ёсны давталтад хуурамч эерэг өгдөг):
  //   · таслалаар жагсаасан ≥5 богино зүйлийн дунд ИЖИЛ зүйл дахин гарсан — «төсөл, ашиглалтын нөхцөл, төрөл, төлөв, төсөл, …»
  //   · ИЖИЛ өгүүлбэр (≥4 үг) шууд дараалан давтагдсан
  if (listLoop(text) || repeatedSentence(text) || wordLoop(text)) {
    hits.collapse = (hits.collapse ?? 0) + 1;
    total += 1;
  }
  if (lang === 'mn-Cyrl' && LATIN_SENTENCE.test(text)) {
    hits.langmix = 1;
    total += 1;
  } else hits.langmix = 0;
  const words = text.split(/\s+/).filter(Boolean).length;
  return { hits, total, words, perHundredWords: words ? Math.round((total / words) * 10000) / 100 : 0 };
}

export const STYLE_KINDS = [...Object.keys(PATTERNS), 'langmix'];

export function summarizeStyle(list) {
  const n = list.length || 1;
  const out = {
    n: list.length,
    withIssues: list.filter((s) => s.total > 0).length,
    avgPerHundredWords: Math.round((list.reduce((a, s) => a + s.perHundredWords, 0) / n) * 100) / 100,
    byKind: {},
  };
  for (const k of STYLE_KINDS) out.byKind[k] = list.reduce((a, s) => a + (s.hits[k] ?? 0), 0);
  return out;
}
