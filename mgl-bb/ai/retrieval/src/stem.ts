  'iin', 'iig', 'yn', 'yg', 'aar', 'eer', 'oor', 'iar',
  'aas', 'ees', 'oos', 'ias', 'tai', 'tei', 'toi', 'ruu',
  'khaar', 'haar', 'heer', 'hoor', 'san', 'sen', 'son', 'dag', 'deg', 'dog',
  'aad', 'eed', 'ood', 'val', 'vel', 'vol', 'na', 'ne', 'no',
  'kh', 'ch', 'd', 't', 'j', 'h',
