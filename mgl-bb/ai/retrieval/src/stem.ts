const MIN_STEM = 4;

function isLetters(t: string): boolean {
  return /^\p{L}+$/u.test(t);
}

/** Эхний таарсан залгаврыг хасна (язгуур ≥ MIN_STEM); таарахгүй бол `null`. */
function stripSuffix(token: string): string | null {
  for (const s of SUFFIXES) {
    if (token.length - s.length >= MIN_STEM && token.endsWith(s)) return token.slice(0, -s.length);
  }
  return null;
}

/**
 * Сул эгшиг гээх — «…C V C» төгсгөл → «…C C»: «даамал» → «даамл», «төсөл» → «төсл»,
 * «зураг» → «зург», «ажил» → «ажл» (сүүлийнх богино тул гарахгүй).
 */
function dropFleetingVowel(stem: string): string | null {
  const n = stem.length;
  if (n < MIN_STEM + 1) return null;
  const c1 = stem[n - 3]!;
  const v = stem[n - 2]!;
  const c2 = stem[n - 1]!;
  if (!CONSONANT.test(c1) || !VOWEL.test(v) || !CONSONANT.test(c2)) return null;
  return stem.slice(0, n - 2) + c2;
}

/**
 * Гийгүүлэгчийн давхарт төгссөн язгуур («даамл», «барилг») — нэрлэхийн хэлбэр рүү хүрэх угтвар:
 * сүүлийн гийгүүлэгчийг хасна («даамл» → «даам» → «даамал»-д таарна).
 */
function dropClusterTail(stem: string): string | null {
  const n = stem.length;
  if (n < MIN_STEM + 1) return null;
  // Латин орлуулгын хоёр үсэгт авиа («ch», «sh», «kh», «ts», «zh») нь НЭГ гийгүүлэгч — таслахгүй.
  if (/(?:ch|sh|kh|ts|zh)$/.test(stem)) return null;
  if (!CONSONANT.test(stem[n - 1]!) || !CONSONANT.test(stem[n - 2]!)) return null;
  return stem.slice(0, n - 1);
}

/**
 * ⚠️ ГОЛ ФУНКЦ.  Токены НЭМЭЛТ угтварын хувилбарууд (эх токен ОРОХГҮЙ), ≥4 тэмдэгт, давхардалгүй.
 * Тоо, богино (<5) эсвэл үсэг бус токенд хоосон.
 */
export function stemVariants(token: string): string[] {
  const t = token.toLowerCase();
  if (t.length < MIN_STEM + 1 || !isLetters(t)) return [];
  const out = new Set<string>();
  const add = (v: string | null): void => {
    if (v !== null && v.length >= MIN_STEM && v !== t) out.add(v);
  };
  const stem = stripSuffix(t);
  const base = stem ?? t;
  add(stem);
  add(dropFleetingVowel(base));
  add(dropClusterTail(base));
  return [...out];
}
