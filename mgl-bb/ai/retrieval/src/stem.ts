  'хаар', 'хээр', 'хоор', 'хөөр', 'сан', 'сэн', 'сон', 'сөн', 'даг', 'дэг', 'дог', 'дөг',
  'аад', 'ээд', 'оод', 'өөд', 'вал', 'вэл', 'вол', 'вөл', 'на', 'нэ', 'но', 'нө',
