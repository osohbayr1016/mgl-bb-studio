/**
 * Зохиогчийн хяналтын төсөл (`projects.asr_only`) — харагдац + үүсгэх дүрэм.
 *
 * Нэг газар байлгана: жагсаалт/тоолуур болон тайлан үүсгэх шүүлт
 * эндээс л орно.  Өөр query дээр давтвал нэг нь мартагдана.
 *
 * `p` alias-тай `projects` мөр дээр хэрэглэнэ.
 */

/** Төслүүд / sidebar / dashboard — ЗХ-ийн төсөл ОГТ гарахгүй. */
export const NOT_ASR_ONLY_SQL = `COALESCE(p.asr_only, 0) = 0`;

/**
 * ЗХ-д оролцохоо БОЛЬСОН төсөл (`projects.asr_merged_into`, миграц 0340).
 *
 * Нэг барилга ERP дээр ангилал тус бүрээр тусдаа `projects` мөртэй
 * (EVERGREEN = AZ #41 ба ZA #37) бөгөөд талбайн хяналт нь хоёуланд нь
 * бүртгэгдэж, инженер аль нь болохыг таамаглах байдалд хүрдэг.  Нэгтгэсэн
 * тохиолдолд ЭХ мөр нь энэ багананд ЗОРИЛТЫН id-г тээж, ЗХ-ийн бүх
 * гадаргуугаас (сонголтын цонх, `/app/asr` самбар, хуваарь) арилна.
 *
 * ⚠️ Энэ нь ЗӨВХӨН зохиогчийн хяналтын шүүлт.  Төсөл өөрөө ХЭВЭЭР —
 *    Төслүүд хуудас, явц, паспорт, Drive, тайлан бүгд хөндөгдөхгүй.
 *    Устгал БИШ: `asr_merged_into = NULL` болгоход бүх зүйл буцна.
 */
export const ASR_NOT_MERGED_SQL = `p.asr_merged_into IS NULL`;

/**
 * Шинэ ЗХ тайлан үүсгэх СЕРВЕРИЙН хаалга: БҮХ төсөл (ангилал харгалзахгүй),
 * нэгтгэгдсэнээс бусад.  Хилийн шугам нь дүр (`ASR_ROLES`), ангилал БИШ —
 * төслийн хуудасны ЗХ табаас ямар ч төсөл дээр тайлан үүсгэж болно.
 *
 * ⚠️ «Шинэ тайлан» товчны СОНГОЛТЫН жагсаалт (`GET /author-supervision/projects`)
 *    нь 2026-09-25-аас ЯВЦУУ — `ASR_SUMMARY_VISIBLE_SQL` (доор), өөрөөр хэлбэл
 *    `/app/asr` самбарт харагддаг ЗХ-ийн гэрээтэй төслүүд л.  Эзний шийдвэр:
 *    бусад төсөл тэр dropdown-д гарахгүй; шинэ төслийг ЗХ-д «тодорхойлох»
 *    тусдаа тохиргоо ОДООХОНДОО хэрэггүй.
 */
export function isAsrCreateEligible(row: {
  asr_only?: number | null;
  category?: string | null;
  asr_merged_into?: number | null;
}): boolean {
  return row.asr_merged_into == null;
}

/**
 * `/app/asr`-ийн төслийн самбар: ЗХ-ийн зориулалттай (`asr_only`), засварын
 * (ZA), эсвэл ядаж нэг тайлантай төсөл.  Бүх төслийг гаргавал самбар
 * компанийн бүх төслийн жагсаалт болж, талбайн хяналт хийдэг цөөн төсөл
 * нь замхарна — шинэ төсөл дээр анхны тайлан хадгалагдмагц энд гарч ирнэ.
 *
 * «Шинэ тайлан» товчны төслийн сонголт ч (2026-09-25-аас) ЯГ энэ дүрмийг
 * хэрэглэнэ — самбар ба сонголт нэг л жагсаалт.
 *
 * Нэгтгэгдсэн төсөл энд ч гарахгүй: тайлангууд нь зорилт руу шилжсэн тул
 * «ядаж нэг тайлантай» нөхцөл ажиллахаа больсон ч, ZA ангилалтай эх мөр
 * (ирээдүйн нэгтгэлт) тоолуургүй хоосон мөр болж үлдэхээс сэргийлнэ.
 */
export const ASR_SUMMARY_VISIBLE_SQL =
  `${ASR_NOT_MERGED_SQL}
   AND (COALESCE(p.asr_only, 0) = 1 OR p.category = 'ZA'
        OR EXISTS (SELECT 1 FROM author_supervision_reports r WHERE r.project_id = p.id))`;
