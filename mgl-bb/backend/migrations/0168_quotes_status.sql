-- =============================================================
-- Үнийн саналын СТАТУС — funnel / win-rate тооцох суурь
-- =============================================================
-- ЮУНЫ ТӨЛӨӨ:
-- MGL жилд ~300 үнийн санал явуулж ~100-ыг нь гэрээ болгодог. Хэдийг явуулж
-- хэдийг авсан, хэдэн төгрөгний санал явуулж хэдэн төгрөгний гэрээ хийснийг
-- апп-аас харах шаардлага гарсан. v2 схем (0128) нь баримт БИЧИХ талдаа
-- төвлөрсөн тул амьдралын мөчлөгийн багана огт байхгүй байв.
--
-- ⚠️ v1 (0083) СХЕМИЙГ СЭРГЭЭХГҮЙ. Тэр нь `draft/submitted/approved/rejected/
--    expired` гэсэн ХАРИЛЦАГЧИЙН БАТАЛГААНЫ мөчлөгтэй байсан (үйлчлүүлэгч
--    өөрөө нэвтэрч зөвшөөрдөг). Одоо ийм харилцагчийн гадаргуу БАЙХГҮЙ —
--    `/api/quotes/*` бүхэлдээ `requireAdmin()`. Эндэх статус нь ЗӨВХӨН
--    борлуулалтын юүлүүрийн шат:
--
--      draft  → Ноорог, хараахан явуулаагүй  (юүлүүрт ОРОХГҮЙ)
--      sent   → Захиалагч руу явуулсан
--      active → Гэрээ болсон / идэвхтэй       (юүлүүрийн ХУВААРЬ)
--      lost   → Амжилтгүй болсон
--
--    win_rate = active / (sent + active + lost)
--
--    `expired` ЗОРИУД БАЙХГҮЙ: v2-т `validity_days` / `expires_at` гэж юу ч
--    байхгүй тул хугацаа дуусахыг тооцох эх сурвалж алга — хиймэл статус
--    болно. Хэрэгтэй бол эхлээд хүчинтэй хугацааны талбар нэм.
--
-- ⚠️ CHECK ХЯЗГААРЛАЛТ ТАВИАГҮЙ. SQLite-д `ALTER TABLE … ADD COLUMN` дээр
--    CHECK нэмэх боломжгүй; CHECK-тэй болгох цорын ганц зам нь хүснэгтийг
--    бүхэлд нь rebuild хийх (path B, репогийн үндсэн CLAUDE.md-г үз) — энэ
--    үнэ цэнэд тохирохгүй эрсдэл. Валидац нь `routes/quotes.ts`-ийн
--    `QUOTE_STATUSES` дээр — шинэ статус нэмэхэд ТЭНД нэмнэ.
--
-- `contract_amount` — ГЭРЭЭНИЙ дүн, `total_amount` (САНАЛ болгосон дүн)-аас
-- ТУСДАА. Хэлэлцээрийн дараа гэрээний дүн саналаас өөр болдог тул «хэдэн
-- төгрөгний гэрээ хийгдсэн» гэдгийг саналын дүнгээр орлуулж болохгүй.
-- `active` руу шилжихэд `total_amount`-оор өгөгдмөлөөр дүүрч, гараар засагдана.
--
-- ⚠️ `total_amount` нь клиентийн тооцоолсон КЭШ бөгөөд браузераар нээгээгүй
--    санал дээр NULL байна (0128-ын тайлбарыг үз). Иймд юүлүүрийн дүн бодоход
--    NULL-ийг 0 гэж БҮҮ тооц — `GET /api/quotes/funnel` нь тэдгээрийг
--    `amount_missing_count`-оор тусад нь тоолж буцаадаг.
-- =============================================================

ALTER TABLE quotes ADD COLUMN status TEXT NOT NULL DEFAULT 'draft';
ALTER TABLE quotes ADD COLUMN status_changed_at TEXT;
ALTER TABLE quotes ADD COLUMN contract_amount REAL;

-- Юүлүүрийн үндсэн хайлт: статусаар бүлэглээд огнооны мужаар шүүнэ.
CREATE INDEX IF NOT EXISTS idx_quotes_status ON quotes(status, doc_date);
