-- =============================================================
-- 0243_bim_session_drop_split.sql — АЛДАГДЛЫН ТООЛУУРЫГ ХОЁР ЭХ
-- СУРВАЛЖААР САЛГАВ (ХЭМЖИГЧ vs ХУРИМТЛАГЧ)
-- =============================================================
--
-- ЗАСЧ БУЙ АЛДАА (амьд хэмжилтээр батлагдсан, 2026-09-01).
--   `bim_sessions.dropped_count` НЭГ багана байсан бөгөөд түүн рүү ХОЁР
--   ХООРОНДОО НИЙЦГҮЙ дүрэм бичдэг байв:
--     • `upsertBimSession`  → MAX(хуучин, клиентийн НИЙЛБЭР тоолуур)
--     • `bumpSessionCounters` → багана = багана + серверийн татгалзал
--   Хэмжилт: POST1 (клиент=0, 3 муу гүйлгээ) → сервер 3 нэмнэ → багана=3.
--   POST2 (клиент=5, цэвэр) → MAX(3,5) → багана=5.  ҮНЭН НИЙЛБЭР нь 8.
--   Гурван алдагдал ЧИМЭЭГҮЙ УСТСАН — багана нь аль жижиг эх сурвалжийг
--   нь ШИНГЭЭДЭГ.  ~20 машины цуглуулга ЗӨВ эсэхийг хэмжих ЦОРЫН ГАНЦ
--   хэрэгсэл тул энэ нь эгзэгтэй.
--
-- ШИЙДЭЛ: нэг багана ХУРИМТЛАГДСАН ХЭМЖИГЧ ба НЭМЭГДДЭГ ТООЛУУР хоёрыг
--   ЗЭРЭГ үүрч ЧАДАХГҮЙ.  Тиймээс хоёр болгож салгав:
--     • `client_dropped_count` — клиент өөрөө зарласан НИЙЛБЭР (локал
--       буферийн халилт, Revit унасан).  Клиент явж буй нийлбэрээ
--       илгээдэг тул MAX (сүүлийн бичигч ялах) нь ЗӨВ дүрэм.
--     • `server_dropped_count` — СЕРВЕР өөрөө татгалзсан/бичиж чадаагүй
--       мөр.  Багц бүрт НЭМЭГДЭНЭ (+=), хэзээ ч MAX хийхгүй.
--   `dropped_count` нь ХЭВЭЭР үлдэнэ, гэхдээ одооноос ГАРГАЖ АВСАН НИЙТ
--   ДҮН: `client_dropped_count + server_dropped_count`.  Хоёулаа бичигч
--   (`lib/bimEvents.ts`-ийн upsert ба bump) түүнийг бүрэлдэхүүн хэсгүүдээс
--   нь ДАХИН БОДОЖ бичдэг тул аль ч эх сурвалж нөгөөгөө дарж чадахгүй.
--   ⚠️ `dropped_count`-д ӨӨР ГАЗРААС БҮҮ БИЧ.  Шинэ алдагдлын эх сурвалж
--      гарвал ГУРАВ ДАХЬ багана нэмээд нийлбэрт нь оруул.
--
-- ⚠️ GENERATED VIRTUAL болгож чадахгүй: тэр нь хүснэгтийг ДАХИН БАРИХЫГ
--    шаардана, `bim_sessions` нь дөрвөн хүүхэд хүснэгтийн эцэг.  Инвариантыг
--    `bimEvents.test.ts`-ийн бодит SQLite тест барина (3-аас хойш 5 → 8).
--
-- ⚠️ ЗАСВАРЫН УТГА: хуучин мөрүүдийн `dropped_count` нь аль хэдийн ХОЛИЛДСОН
--    (аль нэг эх сурвалж нь дарагдсан) тул түүнийг клиентийн талд бүхэлд нь
--    оноож, серверийнхийг 0 болгоно.  Энэ нь ШИНЭ мэдээлэл зохиохгүй —
--    хуучин утга нь ҮНЭНИЙ ДООД ХЯЗГААР хэвээр үлдэнэ.  Production дээр
--    `bim_sessions` нь 0 мөртэй (2026-09-01-ний хэмжилт) тул нөлөө ТЭГ.

ALTER TABLE bim_sessions ADD COLUMN client_dropped_count INTEGER NOT NULL DEFAULT 0;

ALTER TABLE bim_sessions ADD COLUMN server_dropped_count INTEGER NOT NULL DEFAULT 0;

UPDATE bim_sessions SET client_dropped_count = dropped_count WHERE dropped_count > 0;
