-- Зохиогчийн хяналт: УЛААН ДЭВТРИЙН гарын үсгийн баталгаа.
--
-- Талбайд очих бүрд захиалагч/гүйцэтгэгчийн «улаан дэвтэр» (барилгын
-- ажлын журнал) дээр зохиогчийн хяналтын тэмдэглэл бичиж, гарын үсэг
-- зуруулах ёстой.  Энэ нь тайлангаас ТУСДАА амьдралын мөчлөгтэй:
--
--   зураггүй  ->  «Гарын үсэг дутуу»
--   зурагтай  ->  «Гарын үсэг зурагдсан» (баталгаажуулалт хүлээж байна)
--   баталгаажсан -> «Улаан дэвтэр баталгаажсан»
--
-- Төлөв нь ХАДГАЛАГДДАГГҮЙ, доорх хоёр баганаас ГАРГАН АВНА
-- (routes/authorSupervision.ts shapeRow): баталгаажсан огноо байвал
-- verified, зураг байвал signed, үгүй бол missing.  Тусдаа status багана
-- бол зурагтай нь зөрөх боломжтой хоёр дахь эх сурвалж болно.
--
-- Тайлангийн draft/submitted/approved мөчлөгийг ХӨНДӨХГҮЙ: гарын үсэггүй
-- ч илгээнэ, батална, PDF гаргана (эзний урсгал 2026-09-10).  Зөвхөн
-- тайлан дээр тэр дутуу нь ИЛ харагдана.
--
-- red_book_photo_url  -- /media/<key>, улаан дэвтрийн хуудасны зураг.
--                        Тайлангийн хөлдөлтөөс ГАДУУР — илгээсний дараа
--                        ч зохиогч нөхөж хавсаргана (PATCH /:id/red-book).
-- red_book_verified_by -- users.id.  REFERENCES ЗОРИУД БАЙХГҮЙ: users
--                        хүснэгтэд шинэ FK ирмэг нэмэх нь path-B rebuild
--                        болон DELETE /api/users/:id-ийн гар устгалтад
--                        нэг мөр нэмнэ; нэрийг LEFT JOIN-оор уншдаг тул
--                        устсан хэрэглэгч зүгээр л NULL нэр болно.
-- red_book_verified_at -- ISO UTC.  Баталгаажуулагч = canReview
--                        (админ, эсвэл тайланд орсон багийн senior).
