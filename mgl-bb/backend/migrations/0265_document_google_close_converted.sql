-- Хөрвүүлж үүсгэсэн хуучин Google холболтуудыг хаана (2026-09-07).
--
-- Яагаад: анхны хувилбар нь .docx-ийг Google Doc болгож ХӨРВҮҮЛЖ байсан
-- бөгөөд Google-ийн хөрвүүлэгч Word-ийн агуулгын жагсаалтын tab-stop болон
-- цэгэн залгаасыг задалдаг тул баримтын бүтэц эвдэрч уншигдахгүй болж байв.
-- Одоо .docx/.xlsx/.pptx нь эх хэлбэрээрээ (Office editing mode) суудаг.
--
-- `ensureGoogleFile` нь АМЬД холболт олдвол түүнийг ДАХИН АШИГЛАДАГ тул
-- энэ мөрүүдийг хаахгүй бол хуучин, эвдэрсэн хуулбар мөнхөд үлдэнэ.
-- Хаасны дараа дараагийн нээлт шинээр, хөрвүүлэлгүйгээр үүсгэнэ.
--
-- Аюулгүй эсэх: энэ миграцыг бичих үед продакшнд ганц мөр байсан бөгөөд
-- `synced_revision_id` нь NULL — өөрөөр хэлбэл Google дээрх хуулбараас
-- архив руу ЮУ Ч буугаагүй тул алдагдах засвар байхгүй.  `preview_key`-г
-- мөн цэвэрлэнэ: тэр PDF нь эвдэрсэн хөрвүүлэлтээс гарсан.
--
-- Үлдэц: хаагдсан мөрийн Drive хуулбар эзэмшигчийн Drive дээр өнчин үлдэнэ
-- (энд SQL-ээс Drive рүү хандах боломжгүй).  Ганц файл тул гараар устгаж
-- болно; шинэ урсгал дээр `closeMappings` нь хогийн саванд зөв хийдэг.
UPDATE document_google_files
SET status = 'closed', preview_key = NULL
WHERE status = 'open';
