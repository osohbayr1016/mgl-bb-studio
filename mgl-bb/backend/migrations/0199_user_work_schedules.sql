--   • 6–8 сард (жил бүр) бүгд 08:00–17:00 хэвээр — «5.31 хүртэл энэ
--     шинэчлэлт ажиллана, 6.1-нээс 8-5 болго».
--   • 9-р сарын 1-ний ДАРААХ солилт нь МАРГААШААС хүчинтэй.
