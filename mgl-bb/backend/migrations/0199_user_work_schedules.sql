-- ЯАГААД `users` ХҮСНЭГТИЙГ ДАХИН БАРИАГҮЙ ВЭ (хамгийн чухал шийдвэр)
-- ────────────────────────────────────────────────────────────────────────────
-- `users.work_schedule` нь
--     TEXT NOT NULL DEFAULT 'standard' CHECK(work_schedule IN ('standard','early'))
-- (миграци 0136:97-98).  CHECK нь FK-ээс ялгаатай нь D1 дээр НӨХЦӨЛГҮЙ
-- мөрдөгддөг тул `'mid'` бичих гэсэн оролдлого ЗААВАЛ унана.  Түүнийг
-- өргөтгөх ганц зам бол хүснэгтийг бүтнээр rebuild хийх — `users` нь 19
-- ON DELETE CASCADE хүүхэдтэй бөгөөд `migrations apply` доторх транзакцад
-- cascade НЬ АЖИЛЛАДАГ (CLAUDE.md-ийн «path B» хэсгийг үз).  Өөрөөр хэлбэл
-- 3 дахь ээлж нэмэхийн тулд бүх ирц, явц, чөлөө, оноог эрсдэлд оруулах
-- болно.  Нэг сонголтын төлөө хийх ажил БИШ.
--
-- ⚠️ Иймд `users.work_schedule` баганад ЭНЭ МИГРАЦИ ОГТ ХҮРЭХГҮЙ.  Тэр багана
--    одооноос «энэ хүн 2026 оны 9-р сараас ӨМНӨ ямар ээлжтэй байсан бэ»
--    гэсэн ТҮҮХЭН fallback болж хөлдөнө (`accent_color`, `tv_kiosk`-той
--    адил үхмэл биш — ХУУЧИН огноог зөв тайлагнахад хэрэгтэй).
--
-- ────────────────────────────────────────────────────────────────────────────
-- ЯАГААД ЭФФЕКТИВ ОГНООТОЙ ХҮСНЭГТ ВЭ (зүгээр нэг багана биш)
-- ────────────────────────────────────────────────────────────────────────────
--   1) «Одоо сонго, 9-р сарын 1-нээс хүчинтэй» гэдэг нь мөн чанараараа
--      огноотой холбоотой өгөгдөл.
--   2) ⚠️ ОДОО БАЙГАА АЛДААГ ЗАСНА: `routes/attendance.ts:2223` нь ӨНГӨРСӨН
--      өдрийн тайланг ажилтны ӨНӨӨДРИЙН хадгалсан ээлжээр дахин боддог.
--      Тиймээс хүн ээлжээ солиход өнгөрсөн сарын «төлөвлөсөн ирэх цаг» ба
--      хоцролтын waiver нь ХОЙШОО өөрчлөгддөг байсан — атал хоцролтын минут
--      нь clock-in дээр snapshot хийгдсэн хэвээр.  Түүхтэй болсноор тайлан
--      тухайн өдөр ЯГ ямар ээлж үйлчилж байсныг мэддэг болно.
--   3) Аудит: хэн, хэзээ, ямар ээлж сонгосон нь үлдэнэ (`created_by` нь
--      админ ажилтны өмнөөс өөрчилсөн тохиолдлыг ялгана).
--
-- ХАМРАХ ХҮРЭЭ: зөвхөн ирц/хоцролт/чөлөөний цонх.  Цалин бодох модуль
-- системд БАЙХГҮЙ (`payroll_*` хүснэгтүүд 0036-аас хойш уншигч, бичигчгүй) —
-- мөнгөн дүн нь зөвхөн хоцролтын торгууль (`late_penalty_per_minute`).
--
-- ИДЕМПОТЕНТ: `CREATE TABLE IF NOT EXISTS` + `CREATE INDEX IF NOT EXISTS`.
-- Мөр НЭГ Ч оруулахгүй — мөргүй байх нь «хуучин баганаа мөрд» гэсэн утгатай
-- бөгөөд яг одоогийн зан төлөвийг хадгална.  Тиймээс энэ миграци production
-- дээр ажиллахад ажиглагдах өөрчлөлт ГАРАХГҮЙ; өөрчлөлт нь ажилтан өөрөө
-- сонголтоо хийснээр эхэлнэ.
--
-- ⚠️ D1 нь runtime дээр FK-ийг мөрддөггүй тул `DELETE /api/users/:id` дээр
--    энэ хүснэгтийн мөрийг ГАРААР устгана (`routes/users.ts` — тэнд бичсэн).
-- ============================================================================

CREATE TABLE IF NOT EXISTS user_work_schedules (
  id             INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id        INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- ⚠️ `users.work_schedule`-аас ЯЛГААТАЙ нь 'mid' зөвшөөрөгдөнө.
  schedule       TEXT NOT NULL CHECK (schedule IN ('standard', 'early', 'mid')),
  -- UB YYYY-MM-DD.  ЭНЭ ӨДРӨӨС ЭХЛЭН хүчинтэй (тухайн өдрийг ОРУУЛААД).
  effective_from TEXT NOT NULL,
  created_at     TEXT NOT NULL DEFAULT (datetime('now')),
  -- Хэн бичсэн: ажилтан өөрөө, эсвэл админ түүний өмнөөс.
  created_by     INTEGER REFERENCES users(id) ON DELETE SET NULL,
  -- Нэг өдөрт нэг хүнд НЭГ мөр — сонголтоо хэд ч удаа өөрчилсөн UPSERT-ээр
  -- дарж бичигдэнэ (9-р сарын 1 хүртэл бодож үзэх эрх нээлттэй байх ёстой).
  UNIQUE (user_id, effective_from)
);

CREATE INDEX IF NOT EXISTS idx_user_work_schedules_user
  ON user_work_schedules (user_id, effective_from);
