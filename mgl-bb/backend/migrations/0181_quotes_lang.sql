-- =============================================================
-- Үнийн саналын ХЭЛ + англи хувилбарын эх холбоос (lang / source_quote_id)
-- =============================================================
-- ЮУНЫ ТӨЛӨӨ:
-- «Англи хувилбар үүсгэх» (POST /api/quotes/:id/translate) нь монгол саналын
-- ажлын дэвтрийг орчуулж ШИНЭ, ТУСДАА quotes мөр болгож хадгална. Ингэснээр
-- редактор, autosave, хэвлэх/PDF, статусын машин бүгд одоо байгаа нэг-баримтын
-- замаа ЯМАР Ч ӨӨРЧЛӨЛТГҮЙ ашиглана — орчуулга нь зүгээр л бас нэг санал.
--
--   lang            — 'mn' | 'en'. Өгөгдмөл 'mn' тул одоогийн бүх мөр монгол
--                     хэвээр. ⚠️ CHECK ХЯЗГААРЛАЛТ ТАВИАГҮЙ: SQLite-д
--                     `ALTER TABLE … ADD COLUMN` дээр CHECK нэмэх боломжгүй,
--                     rebuild (path B) нь энэ үнэ цэнэд тохирохгүй (0168-ын
--                     толгойтой ижил шалтгаан). Жинхэнэ валидац нь
--                     routes/quotes.ts-ийн `QUOTE_LANGS` — шинэ хэл нэмэхэд
--                     ТЭНД нэмнэ.
--   source_quote_id — англи хувилбарын ЭХ (монгол) саналын id. NULL = энгийн
--                     (эх) санал. Нэг эхээс НЭГ л англи хувилбар үүсдэг
--                     (translate маршрут 409 EXISTS буцаадаг).
--
-- ⚠️ ЮҮЛҮҮР (GET /api/quotes/funnel) нь `source_quote_id IS NULL`-ээр шүүдэг
--    БОЛСОН: англи хувилбар нь эх саналтайгаа НЭГ хэлцэл тул давхар тоолбол
--    «хэдэн санал явуулав», «хэдэн төгрөгний санал» хоёул хийсвэрээр өснө.
--
-- ⚠️ D1 нь тунхагласан FK-г ажиллах үедээ ШАХДАГГҮЙ тул доорх
--    `ON DELETE SET NULL` нь зөвхөн баримтжуулалт. Тиймээс
--    DELETE /api/quotes/:id нь эх саналыг устгахын өмнө
--    `UPDATE quotes SET source_quote_id = NULL WHERE source_quote_id = ?`-ийг
--    ГАРААР гүйцэтгэнэ (репогийн manual-cleanup конвенц — email.ts г.м.).
-- =============================================================

ALTER TABLE quotes ADD COLUMN lang TEXT NOT NULL DEFAULT 'mn';
ALTER TABLE quotes ADD COLUMN source_quote_id INTEGER REFERENCES quotes(id) ON DELETE SET NULL;

-- Эх санал → англи хувилбарыг хайх (translate-ийн 409 EXISTS шалгалт,
-- DELETE-ийн гар цэвэрлэгээ).
CREATE INDEX idx_quotes_source_quote ON quotes(source_quote_id);

-- ⚠️ «Нэг эхээс НЭГ англи хувилбар»-ыг ӨГӨГДЛИЙН САНГААР шахна. Маршрутын
--    EXISTS шалгалт нь AI орчуулгын (хэдэн секунд) ӨМНӨ явдаг тул зөвхөн
--    түүнд найдвал хоёр таб/хоёр админ зэрэг дарахад ХОЁР англи хувилбар
--    үүсэх цонх нээлттэй үлдэнэ. Хэсэгчилсэн (partial) индекс тул монгол
--    мөрүүдийн `source_quote_id IS NULL` давхардал АСУУДАЛГҮЙ.
--    Маршрут нь энэ зөрчлийг барьж яг тэр 409 EXISTS болгож хөрвүүлдэг.
CREATE UNIQUE INDEX idx_quotes_source_quote_en
  ON quotes(source_quote_id) WHERE lang = 'en';
