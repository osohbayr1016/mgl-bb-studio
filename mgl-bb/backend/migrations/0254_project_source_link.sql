-- =============================================================
-- 0254_project_source_link.sql — Төслийн бүтэц хуулсан эх сурвалж
-- =============================================================
--
-- Засварын гэрээ (`category='ZA'`) ирэхэд ижил барилгын блок → зураг →
-- бүрдэл → даалгаврын мод, багийн хувь хуваарилалт аль хэдийн НӨГӨӨ
-- төсөл дээр байдаг ч шинэ төсөл дээр админ бүгдийг гараар дахин барьдаг.
-- «Бүтэц хуулах» гарц үүнийг хуулна, энэ багана нь ХААНААС хуулсныг
-- бүрмөсөн тэмдэглэнэ.
--
-- ЯАГААД БАГАНА ХЭРЭГТЭЙ ВЭ?
--   Өнөөдөр ZA төслийг өөрийнх нь засварлаж буй барилгатай холбож буй
--   ганц зүйл бол ТӨСЛИЙН НЭР.  Продакшн дээрх 8 ZA төслийн 4 нь эх
--   төслийнхөө нэртэй огт таарахгүй байна — өөрөөр хэлбэл нэрээр холбох
--   нь одоо ч ажиллахгүй байгаа бөгөөд цаашид ч найдваргүй.  Тодорхой FK
--   байснаар «энэ барилга дээр өмнө нь ямар ажил хийгдсэн бэ?» гэсэн
--   асуултад ганц query-ээр хариулна.
--
-- ЯАГААД `ALTER TABLE ... ADD COLUMN` ВЭ?
--   `projects` бол CASCADE гинжний ЭЦЭГ (~40 хүүхэд хүснэгт).  D1 дээр
--   `migrations apply` нь файлыг гүйлгээнд боож, `PRAGMA foreign_keys`-ыг
--   үл тоомсорлодог тул parent хүснэгтийг дахин барих нь бүх хүүхэд мөрийг
--   УСТГАНА (CLAUDE.md-ийн path-B runbook).  Тиймээс энд ЗӨВХӨН багана
--   нэмнэ — 0143 (`is_pending`), 0211 (`asr_only`)-тэй ижил хэв маяг.
--
-- ҮЙЛ АЖИЛЛАГААНЫ ХОЁР ҮР ДАГАВАР:
--   (a) D1 нь ажиллах үедээ FK-г ХЭРЭГЖҮҮЛДЭГГҮЙ, тиймээс энд бичсэн
--       `ON DELETE SET NULL` нь зөвхөн БАРИМТЖУУЛАЛТ.  Эх төслийг
--       устгахад хүүхэд мөрийн утга өөрөө NULL болохгүй тул
--       `DELETE /api/projects/:id` нь `source_project_id`-г ГАРААР
--       NULL болгох ёстой (email.ts / calendar.ts / repair.ts-ийн
--       «хүүхдээ өөрөө устга» конвенцтой ижил).
--   (b) UNIQUE индекс ЗОРИУДААР БАЙХГҮЙ.  Нэг барилгыг олон удаа засаж
--       болно, өөрөөр хэлбэл нэг эх төсөл олон ZA төслийн эх сурвалж
--       байж бүрэн хэвийн.
--
-- Индекс нь урвуу чиглэлийн уншилтад зориулагдсан: «энэ төслөөс ямар
-- төслүүд үүссэн бэ» (`GET /api/projects/:id/derived`).
-- =============================================================

ALTER TABLE projects ADD COLUMN source_project_id INTEGER REFERENCES projects(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_projects_source_project ON projects(source_project_id);
