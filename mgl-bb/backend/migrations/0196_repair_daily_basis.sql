-- =============================================================
-- 0196_repair_daily_basis.sql — засварын хувь нь ӨДӨР дээр суурилна
-- =============================================================
--
-- ЭЗНИЙ ШИЙДВЭР (2026-08-25):
--   «Ажилтны хувийг ажилласан цагаар нь бодно.  Энэ нь түүний ӨДРИЙН дундаж
--    хувь дээр суурилна.  Хэрэв тухайн ажилтны өдрийн дундаж хувь 1.2% бол,
--    тэр 4 цаг зарцуулсан тохиолдолд өдрийн 0.6%-ийг авна.»
--
--       хувь = ӨДРИЙН_ДУНДАЖ_ХУВЬ × (цаг / 8)
--
--   Мөн `repair_projects.rate_multiplier` (админы гараар тавьдаг үнэ цэнийн
--   үржвэр) ХЭРЭГГҮЙ болсон — бүх дотоод ажил цаг тутамдаа ижил үнэтэй.
--
-- ЮУ ӨӨРЧЛӨГДӨЖ БАЙНА:
--   Тоон үр дүн нь бараг хэвээр: өмнө нь `долоо_хоногийн_ханш × (цаг / 40)`
--   байсан бөгөөд долоо хоног = 5 ажлын өдөр тул нэг цагийн үнэ ЯГ ижил
--   (ханш/40 = (ханш/5)/8).  Өөрчлөгдөж байгаа нь ХЭМЖИХ НЭГЖ ба ХАРАГДАЦ:
--   ажилтан «долоо хоногийн 10%» биш «өдрийн 50%» гэж хардаг болно.
--
-- ЯАГААД ӨГӨГДЛИЙГ ЗАСАХ ХЭРЭГТЭЙ ВЭ:
--   `repair_entries.day_hours` бол ХУВААГЧИЙН snapshot бөгөөд UI нь
--   `hours / day_hours × 100` гэж хувийг гаргадаг (RepairSection.tsx,
--   RepairHistoryTab.tsx).  Production дээр өнөөдөр:
--       day_hours = 40 → 224 мөр   (долоо хоногийн хуваагч)
--       day_hours = 8  →   7 мөр   (0114-ийн анхны утга)
--   Өөрөөр хэлбэл нэг багана ХОЁР өөр утга агуулж байна.  Шинэ мөрүүд 8
--   бичих тул засахгүй бол гурав дахь давхарга үүсэхгүй ч, түүхэн 224 мөр
--   өнөөдрийнхөөс 5 дахин бага хувь харуулсаар үлдэнэ.
--
--   `weekly_avg_pct` нь ханшийн snapshot (UI-д ХЭЗЭЭ Ч рендэрлэгддэггүй,
--   зөвхөн аудитын ул мөр).  Тэр ч мөн адил 5-д хуваагдаж өдрийн ханш болно.
--
--   ⚠️ `computed_pct` буюу БОДИТ ОНОО-г ОГТ ХӨНДӨХГҮЙ.  `user_points` бол
--   дэвтэр — түүхэн оноо хөдлөх ёсгүй.  Энэ миграц нь зөвхөн ХАРАГДАЦЫН
--   нэгжийг жигдрүүлнэ.
--
-- Зөвхөн `day_hours = 40` мөрийг хөндөнө: 8-тай 7 мөр нь аль хэдийн өдрийн
-- суурьтай тул давхар хуваавал буруу болно.  Тиймээс миграц нь ИДЕМПОТЕНТ —
-- хоёр дахь удаа ажиллуулбал таарах мөр олдохгүй.
-- =============================================================

UPDATE repair_entries
   SET weekly_avg_pct = weekly_avg_pct / 5.0,
       day_hours      = 8
 WHERE day_hours = 40;

-- `repair_projects.rate_multiplier` нь ҮХМЭЛ багана болов (2026-08-25).
-- Устгахын тулд хүснэгтийг дахин байгуулах шаардлагатай бөгөөд ямар ч ашиггүй
-- тул `DEFAULT 1`-тэйгээ үлдэнэ — `accent_color`, `tv_kiosk`, `model_xkt_url`
-- зэрэг бусад үлдэгдэл баганын адил.  Байгаа бүх мөрийг 1 болгож жигдрүүлнэ
-- (админ өмнө нь өөр утга тавьсан байвал одооноос хойш нөлөөгүй).
UPDATE repair_projects SET rate_multiplier = 1 WHERE rate_multiplier <> 1;
