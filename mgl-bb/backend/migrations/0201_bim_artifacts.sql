-- ⚠️ BUCKET: `MEDIA_BUCKET` нь `GET /media/:key`-ээр ДЭЛХИЙД НЭЭЛТТЭЙ,
--    баталгаажуулалтгүй (`backend/src/routes/media.ts:55`, `index.ts:193`
--    дээр root-д суусан тул `authMiddleware` хүрэхгүй).  Иймд энд ЗӨВХӨН
--    хувийн `MEETING_BUCKET` зөвшөөрөгдөнө — CHECK-ээр түгжив.
--    Татах зам нь `routes/meetingAudio.ts:23`-ийн ЗАГВАР: worker-ийн ҮНДЭС
--    дээрх маршрут + `purpose`-той, ЯГ ТЭР түлхүүрт уясан богино JWT.
--
-- ⚠️ ТҮЛХҮҮР НЬ АГУУЛГААС ХАМААРНА, СЕРВЕР ТООЦООЛНО.
--    `routes/upload.ts:33`-ийн `${user.sub}-${Date.now()}-${file.name}`
--    схемийг ЭНД ӨВЛӨХГҮЙ: тэр нь ижил байтыг олон удаа хадгалдаг ба
--    хэрэглэгчийн id-г дэлхийд нээлттэй түлхүүрт шингээдэг.
--      r2_key = 'bim_' || sha256          (68 тэмдэгт, ЗУРААСГҮЙ)
--    ⚠️ ЗУРААСГҮЙ нь ЗОРИУДААР: репогийн хувийн-объектын маршрут
--    (`/meeting-audio/:key`) нэг л замын хэсэгтэй таардаг.  `bim/ab/<hash>`
--    гэсэн түлхүүр тэр маршрутаар ХЭЗЭЭ Ч татагдахгүй.
--    СЕРВЕР нь `sha256`-ыг БАЙТААС ӨӨРӨӨ тооцоолж, клиентийн зарласантай
--    тааруулна; таарахгүй бол 400.  Клиентийн хэш бол чимэглэл.
--    ⚠️ `backend/src/` дотор агуулгын хэш ӨНӨӨДӨР БАЙХГҮЙ — SHA-256 нь
--    зөвхөн HMAC/ECDSA/HKDF-д гардаг.  Энэ бол ШИНЭ чадвар.
--
-- ⚠️ REFERENCES ЗАРЛАЛ БАЙХГҮЙ (энэ бүх багцад).  D1 нь runtime дээр FK-г
--    ХЭРЭГЖҮҮЛДЭГГҮЙ тул зарлал ямар ч хамгаалалт өгдөггүй.  Харин
--    `d1 execute --remote --file` (path-B runbook) нь `PRAGMA foreign_keys`-ыг
--    ХҮНДЭТГЭДЭГ бөгөөд тэнд `ON DELETE SET NULL` каскад нь ХҮҮХЭД МӨРИЙН
--    UPDATE болж хувирч, 0206-ын өөрчлөгдөшгүй байдлын trigger-ийг асаана —
--    үр дүнд нь ЭЦГИЙН DELETE БҮХЭЛДЭЭ УНАНА (SQLite 3.53-т дахин үйлдэв).
--    Өнчирсөн заагч нь ЗӨВ зан төлөв: хэрэглэгчийн бүртгэл устсан нь
--    сургалтын өгөгдлийг устгах шалтгаан биш.
--
-- ⚠️ `kind` дээр CHECK ТАВИАГҮЙ — 0190-ийн заншил.  Энэ нь 1B-1-ийн
--    төслөөс ЗОРИУДЫН ЗӨРҮҮ: сая мөртэй append-only хүснэгтийг CHECK
--    өөрчлөхийн тулд ДАХИН БАРИХ нь энэ загварын хийж ЧАДАХГҮЙ цорын
--    ганц зүйл.  Хаалттай багцыг `lib/bimEvents.ts`-ийн
--    `Record<ArtifactKind, …>` бүрэн бичлэгээр барина (`lib/pushSweep.ts:53`
--    дэх `CATEGORY_OF`-ийн заль — шинэ утга нэмэхэд ЭМХЭТГЭЛ УНАНА).
--    Одоогийн утгууд:
--      ELEMENT_DELTA  — нэг flush-ийн бүх гүйлгээний элементийн дэлгэрэнгүй
--                       (gzip JSON, `schema_tag='element-delta/v1'`)
--      PARAM_SNAPSHOT — нэг элементийн параметрийн before/after
--      VIEW_IMAGE     — харагдац/хуудасны PNG
--      SKETCH         — гараар зурсан ноорог
--      IMAGE          — хэрэглэгчийн хавсаргасан зураг
--      PDF            — экспортолсон хуудас
--      REVIT_STATE    — загварын агшин (JSON)
--      TEXT           — урт бичвэр (мөр нь D1-д багтахгүй үед)
--      OTHER

CREATE TABLE IF NOT EXISTS bim_artifacts (
  id           INTEGER PRIMARY KEY AUTOINCREMENT,

  -- 64 тэмдэгт hex, СЕРВЕР тооцоолсон.  Давхардлыг БҮРЭН хаана.
  sha256       TEXT    NOT NULL UNIQUE CHECK (length(sha256) = 64),

  -- ЗӨВХӨН хувийн bucket.  Энэ CHECK нь ГҮЙЦЭТГЭЛИЙН бус АЮУЛГҮЙ
  -- БАЙДЛЫН хаалт, тиймээс нам оврын хүснэгт дээр үлдээв.
  bucket       TEXT    NOT NULL DEFAULT 'meeting' CHECK (bucket IN ('meeting')),
  r2_key       TEXT    NOT NULL UNIQUE,

  media_type   TEXT    NOT NULL DEFAULT 'application/octet-stream',
  kind         TEXT    NOT NULL,
  -- Агуулгын ӨӨРИЙНХ нь гэрээ, ж: 'element-delta/v1'.  Задлагч үүнийг
  -- уншиж байж л blob-ыг тайлна.  Хоосон = гэрээгүй (зураг гэх мэт).
  schema_tag   TEXT    NOT NULL DEFAULT '',
  -- 'identity' | 'gzip'.  Add-in element-delta-г ЗААВАЛ gzip-лэнэ.
  encoding     TEXT    NOT NULL DEFAULT 'identity',

  byte_size    INTEGER NOT NULL CHECK (byte_size > 0),
  -- Дотор нь хэдэн бичлэг байгаа (элемент, гүйлгээ).  0 = хамаарахгүй.
  item_count   INTEGER NOT NULL DEFAULT 0,

  -- Бүгд REFERENCES-ГҮЙ, өнчирч болно.
  session_id   INTEGER,        -- bim_sessions.id
  project_id   INTEGER,
  uploaded_by  INTEGER,

  created_at   TEXT    NOT NULL DEFAULT (datetime('now')),

  -- Redaction: R2-оос байтыг устгасны ДАРАА энд тэмдэглэнэ.  Мөр нь
  -- ХЭЗЭЭ Ч устахгүй — «энд ямар нэг зүйл байсан» гэдэг нь өөрөө баримт.
  redacted_at      TEXT,
  redacted_by      INTEGER,
  redaction_reason TEXT
);

-- `sha256` ба `r2_key` дээр ТУСДАА индекс ХЭРЭГГҮЙ — UNIQUE нь өөрөө
-- индекс үүсгэдэг.
CREATE INDEX IF NOT EXISTS idx_bim_artifacts_kind
  ON bim_artifacts (kind, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_bim_artifacts_session
  ON bim_artifacts (session_id) WHERE session_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_bim_artifacts_redacted
  ON bim_artifacts (redacted_at) WHERE redacted_at IS NOT NULL;
