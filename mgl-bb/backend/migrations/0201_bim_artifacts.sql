--    байх ЁСТОЙ.  Нэг хүний нэрлэсэн үйл ажиллагааны жагсаалтыг ӨӨР хүнд
--    ХЭЗЭЭ Ч буцаахгүй.  Эзэн «мэдэгдэнэ, татгалзах товч байхгүй» гэж
--    шийдсэн (2026-08-27) — тэр нь ЭНЭ дүрмийг СУЛРУУЛАХГҮЙ, эсрэгээрээ
