-- 0143 — «Гэрээ хэлэлцээрийн шатанд» гэсэн тэмдэг.
--
-- Гэрээ нь хараахан байгуулагдаагүй, хэлэлцээрийн шатанд яваа төслийг
-- тэмдэглэнэ.  Ийм төсөл Timeline дээр шараар тодорч, компанийн «идэвхтэй
-- төсөл»-ийн тоо болон хугацаа хэтэрсэн даалгаврын жагсаалтаас хасагдана —
-- гэрээгүй ажлыг гүйцэтгэлийн үзүүлэлтэд оруулах нь тоог гуйвуулна.
--
-- ⚠ ЯАГААД `status`-д шинэ утга нэмээгүй вэ?
--   `projects.status`-ийн CHECK нь `('active','completed','archived')`.
--   Түүнийг өргөтгөхийн тулд хүснэгтийг бүхэлд нь дахин барих ёстой бөгөөд
--   `projects` нь blocks → drawings → components → tasks гэсэн CASCADE
--   гинжний ЭЦЭГ.  D1 дээр parent хүснэгт дахин барих нь бүх хүүхэд мөрийг
--   устгах эрсдэлтэй (CLAUDE.md-ийн 0136-гийн runbook-ыг үз).  Шинэ багана
--   нэмэх нь `ALTER TABLE ... ADD COLUMN` — хүснэгт хөндөгдөхгүй, нэг ч мөр
--   эрсдэлд орохгүй.  Мөн `is_asap`-ийн аль хэдийн батлагдсан хэв маягтай
--   ижил байна.
--
-- Анхдагч утга 0: одоо байгаа 24 төслийн нэг нь ч тэмдэглэгдэхгүй.

ALTER TABLE projects ADD COLUMN is_pending INTEGER NOT NULL DEFAULT 0;
