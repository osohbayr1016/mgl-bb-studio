-- =============================================
-- «Дээр бэхлэх» (pin) — ХЭРЭГЛЭГЧ ТУС БҮРИЙН хувийн сонголт.
--
-- Төслүүдийн хуудсанд бэхэлсэн төсөл нь бусад бүх төслөөс дээр гарна.
-- Эрэмбэ:  бэхэлсэн → ASAP → гар эрэмбэ (sort_order) → шинэ нь.
--
-- ⚠ Энэ нь `projects.is_asap`-аас ЯЛГААТАЙ (migration 0105):
--     • ASAP  = админ тавьдаг, БҮХ хүнд улаанаар харагддаг компанийн
--               хэмжээний «яаралтай дуусгах» тэмдэг.
--     • pin   = хувь хүний хавчуурга.  Өөр хэрэглэгчийн жагсаалтад ОГТ
--               нөлөөлөхгүй, тиймээс роль шалгахгүй (инженер, архитектор,
--               ахлах, админ бүгд өөрсдийнхөө жагсаалтыг бэхэлж болно).
--   Хоёулаа «дээр гаргах» ч зорилго нь өөр — нэгийг нөгөөгөөр бүү орлуул.
--
-- ⚠ Админы `sort_order` (гар чирэлт) нь ГЛОБАЛ хэвээр: Төслүүдийн хуудсын
--   «Засах» горимд бэхлэлтийг эрэмбэнд ОРУУЛАХГҮЙ, эс бөгөөс нэг хүний
--   хувийн сонголт бүх компанийн дарааллыг дарж бичих байсан
--   (`ProjectsPage.tsx`-ийн `filtered` эрэмбэлэгчийг үз).
--
-- ⚠ D1 нь runtime дээр FK-г хэрэгжүүлдэггүй тул төсөл устгахад
--   `routes/projects.ts`-ийн `DELETE /:id` энэ хүснэгтийг ГАРААР цэвэрлэнэ.
-- =============================================

CREATE TABLE IF NOT EXISTS project_pins (
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  PRIMARY KEY (user_id, project_id)
);

-- Уншилтын үндсэн зам нь `WHERE user_id = ?` — PK нь user_id-гаар эхэлдэг
-- тул тусдаа индекс шаардлагагүй.  Харин төсөл устгах үеийн
-- `WHERE project_id = ?` цэвэрлэгээнд энэ индекс хэрэгтэй.
CREATE INDEX IF NOT EXISTS idx_project_pins_project ON project_pins(project_id);
