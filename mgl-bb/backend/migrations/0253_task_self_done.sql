-- =============================================================
-- 0253 — «Миний хийх ажил дууссан» хувийн тэмдэглэгээ (ЗӨВХӨН ЗАСВАР)
--
-- Асуудал: засварын төсөл дээр ажилтны хийх хэсэг дуусдаг ч таскийн
-- нийт хувь 100%-д хүрдэггүй (нөгөө хэсгийг өөр хүн/өөр үе шат хийнэ).
-- `/progress/my-tasks` нь `current_progress < 100` бүхнийг «идэвхтэй»
-- гэж үздэг тул тэр таскууд «Миний даалгаврууд»-аас хэзээ ч арилдаггүй
-- бөгөөд ажилтан жагсаалтаа цэвэрлэхийн тулд ХИЙГЭЭГҮЙ хувиа нэмж
-- 100% болгох сэдэлтэй болж байв — өгөгдөл гуйвуулах шууд шахалт.
--
-- Шийдэл: тухайн ХЭРЭГЛЭГЧИЙН хувьд тэр таскийг «би дуусгасан» гэж
-- тэмдэглэх мөр.  Энэ нь ЗӨВХӨН ХАРАГДАЦ:
--   • `progress_entries` үүсгэхгүй, ямар ч хувь бичихгүй;
--   • `weight_percent` БАЙХГҮЙ, ямар ч rollup (PROJECT_LIST_SQL болон
--     түүний 11 хуулбарын аль нь ч) энэ хүснэгтийг УНШИХГҮЙ;
--   • оноо (`user_points`) огт хөдлөхгүй.
-- Өөрөөр хэлбэл төслийн явц, оноо, тайлан бүгд өөрчлөгдөхгүй — зөвхөн
-- тухайн хүний жагсаалтаас мөр нуугдана (буцаах боломжтой).
--
-- ⚠️ Хамрах хүрээ: сервер тал `projects.category = 'ZA'` (Засвар) байхыг
-- шаардана.  Бусад ангиллын төсөл дээр энэ гарц ХААЛТТАЙ — эзний
-- шийдвэр: ердийн ажлын зураг дээр ажилтан өөрөө ажлаа хаах эрхгүй.
--
-- `UNIQUE(task_id, user_id)` — нэг таск дээр хоёр хүн ажиллаж байвал тус
-- тусдаа тэмдэглэнэ, нэгнийх нь нөгөөгийнхөд нөлөөлөхгүй.
-- =============================================================

CREATE TABLE IF NOT EXISTS task_self_done (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  task_id    INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  note       TEXT,
  created_at TEXT DEFAULT (datetime('now')),
  UNIQUE(task_id, user_id)
);

-- Гол унших хэлбэр: `/progress/my-tasks` дээрх «миний бүх тэмдэглэгээ».
CREATE INDEX IF NOT EXISTS idx_task_self_done_user
  ON task_self_done(user_id, task_id);
