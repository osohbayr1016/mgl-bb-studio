-- `assistant_logs`-д аль хэдийн `feedback` (-1/1) ба `corrected` (зөв санааны
-- НЭР) байдаг.  Гэвч тэр хоёр нь «ЯАГААД буруу байсан» гэдэгт хариулдаггүй:
--   • `feedback = -1` нь зөвхөн «муу» гэдгийг хэлнэ, шалтгааныг нь биш.
--   • `corrected` нь хаалттай багц (санааны нэр) — «хариулт нь хэт урт байсан»,
--     «энэ хуудсыг ойлгосонгүй» гэх мэт зүйлийг илэрхийлж ЧАДАХГҮЙ.
-- Тиймээс тусдаа, чөлөөт талбар хэрэгтэй.
