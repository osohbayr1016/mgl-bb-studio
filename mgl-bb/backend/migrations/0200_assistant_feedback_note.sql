-- ⚠️ НУУЦЛАЛ: энэ талбарт ХЭРЭГЛЭГЧИЙН БИЧСЭН текст л орно.  Загварын
-- геометр, элементийн нэр, файлын агуулга ОРОХГҮЙ — `assistant_logs`-ийн
-- бусад талбартай ижил зарчим.  Сервер тал 500 тэмдэгтээр таслана.

ALTER TABLE assistant_logs ADD COLUMN feedback_note TEXT;

-- Долоо хоног тутмын хяналтын ЦОРЫН ГАНЦ асуулт: «энэ долоо хоногт хүмүүс
-- юун дээр гомдоллов?».  Хэсэгчилсэн индекс тул бараг зай эзлэхгүй —
-- тэмдэглэлтэй мөр нь нийт бүртгэлийн маш бага хувь байна.
CREATE INDEX IF NOT EXISTS idx_assistant_logs_notes
  ON assistant_logs (created_at)
  WHERE feedback_note IS NOT NULL;
