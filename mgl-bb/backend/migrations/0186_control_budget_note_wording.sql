-- «Хяналтын төсөв» загварын ХОЁР БИЧВЭРИЙГ ЗАСНА (2026-08-24).
--
--   1. «Тайлбар: Эскиз зураг боловсруулах ажлын нийт дүн ₮…»
--      →  «Тайлбар: Зураг төсөл боловсруулах ажлын нийт дүн ₮…»
--      Шалтгаан: НИЙТ ДҮН нь Ажлын зураг + Эскиз + Гадна тохижилт + судалгаа +
--      экспертиз бүгдийг агуулдаг ба `lib/scopeQuote.ts`-ийн хэсэгчилсэн санал
--      дээр хамрах хүрээ бүр өөр байж болно. Ганц ажлын нэрийг дурдсан бичвэр
--      захиалагчид ХУДАЛ мэдээлэл өгч байв.
--      Мөн `backend/src/lib/quoteTranslate.ts`-ийн тольд энэ бичвэр байхгүй
--      байсан тул англи хуулбар дээр AI-д унаж, мөнгөн дүнгийн өмнөх зай
--      алдагдах эсвэл мөр монголоороо үлдэх эрсдэлтэй байв.
--
--   2. «Тopography М1;500» → «Тopography М1:500» (масштабын тэмдэглэгээ;
--      цэгтэй таслал нь бичгийн алдаа).
--
-- ⚠️⚠️ ЯАГААД ЭНЭ НЬ ГЕНЕРАТОРЫН БҮТЭН ГАРАЛТ БИШ, ЗОРИЛТОТ REPLACE ВЭ:
-- `backend/scripts/gen-control-budget-template.mjs`-ийг одоо дахин үүсгэвэл
-- дээрх хоёроос ГАДНА 131 тоон нүдний `align` нь `right`-аас `center` рүү
-- өөрчлөгдөнө. Тэр зөрүү нь `b2b6116 style(quotes): center quantity and all
-- table numbers` коммитоос үүссэн бөгөөд тэр коммит migration ҮҮСГЭЭГҮЙ тул
-- production дээрх загвар 0185-ынхаа `right` хэвээр байна. Хэмжсэн: генератор
-- vs 0185 = 132 нүд зөрүүтэй, түүний 131 нь ЗӨВХӨН эгнээ.
-- Энэ migration нь тэр асуудлыг ШИЙДЭХГҮЙ, ХӨНДӨХГҮЙ — эзэн нь шийдэх ёстой
-- тусдаа сэдэв. Тиймээс энд ЗӨВХӨН хүсэгдсэн хоёр мөрийг сольж, өөр юуг ч
-- хөндөхгүй.
--
-- ⚠️ Загварын migration нь ЗӨВХӨН ШИНЭ саналд нөлөөлнө. Санал бүр үүсэх үедээ
-- `sheet_json`-оо snapshot авдаг тул АЛЬ ХЭДИЙН үүссэн саналууд хуучин
-- бичвэрээ хадгална (тэдгээрийн англи орчуулга нь `QUOTE_MN_EN_DICT`-ийн
-- ХУУЧИН түлхүүрээр зөв ажиллана — тэр түлхүүрийг БИТГИЙ ХАС).
--
-- ⚠️ УСТГААД-ДАХИН-ОРУУЛАХ БИШ, БАЙРАНД НЬ ШИНЭЧИЛНЭ:
-- `quote_template_history.template_id` нь ON DELETE CASCADE,
-- `quotes.template_id` нь ON DELETE SET NULL. Production D1 нь
-- `PRAGMA foreign_keys = 1` бөгөөд `migrations apply` файл бүрийг гүйлгээнд
-- ороодог тул DELETE хийвэл түүх ба саналуудын холбоос ҮНЭХЭЭР устана.
-- Энд DROP/DELETE огт байхгүй — зөвхөн UPDATE.
--
-- Буцаах: `quote_template_history`-гийн энэ шинэчлэлийн ӨМНӨХ мөрийг сэргээх,
-- эсвэл `replace()`-ийг эсрэгээр нь ажиллуулах.

-- 1) Одоогийн агуулгыг түүхэд хуулна (мөр байхгүй/давхардвал юу ч болохгүй).
INSERT OR IGNORE INTO quote_template_history (template_id, version, sheet_json, variants_json)
SELECT id, version, sheet_json, variants_json
  FROM quote_templates
 WHERE name = 'Хяналтын төсөв (БД 81-16-20)';

-- 2) Байранд нь, ЗОРИЛТОТ хоёр орлуулга.
--    `replace()` нь мөр олдохгүй бол юу ч хийхгүй тул идемпотент.
UPDATE quote_templates
   SET sheet_json = replace(
         replace(
           sheet_json,
           'Тайлбар: Эскиз зураг боловсруулах ажлын нийт дүн ₮',
           'Тайлбар: Зураг төсөл боловсруулах ажлын нийт дүн ₮'
         ),
         'Тopography М1;500',
         'Тopography М1:500'
       ),
       version    = version + 1,
       updated_at = datetime('now')
 WHERE name = 'Хяналтын төсөв (БД 81-16-20)'
   AND (instr(sheet_json, 'Тайлбар: Эскиз зураг боловсруулах ажлын нийт дүн ₮') > 0
     OR instr(sheet_json, 'Тopography М1;500') > 0);

