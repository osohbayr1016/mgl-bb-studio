-- Drive хавтас вэ» гэсэн ХОЛБООСЫГ хадгална.  Хавтасны агуулгыг хүсэлт
-- бүрт Drive API-аас шинээр уншина (routes/projectDrive.ts) — Drive-ын
-- мета өгөгдлийн хуулбар хүснэгт ЗОРИУДААР БАЙХГҮЙ: хуучирсан кэш нь
-- Drive-ын үнэнийг дарах эрсдэлийг л нэмнэ, ашиг өгөхгүй.
--
-- ЯАГААД `ALTER TABLE ... ADD COLUMN` ВЭ?
--   `projects` нь 33 каскад хүүхэдтэй «хөндөж болохгүй» эцэг — дахин
--   байгуулах нь path B-ийн ажил.  Багана нэмэх нь тийм эрсдэлгүй.
--
-- `google_drive_folder_id`   — Drive хавтасны ТОГТВОРТОЙ id (URL БИШ).
--                              NULL = холбогдоогүй.
-- `google_drive_folder_name` — Холбох мөчид Drive-аас уншсан нэр; зөвхөн
--                              тохиргооны дэлгэцэд Drive руу дуудалгүй
--                              харуулахад.  Үнэн нь ҮРГЭЛЖ Drive.
ALTER TABLE projects ADD COLUMN google_drive_folder_id TEXT;
ALTER TABLE projects ADD COLUMN google_drive_folder_name TEXT;
