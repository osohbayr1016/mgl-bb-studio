-- =============================================================
-- Үнийн саналын ГАРАЛ ҮҮСЛЭЭ (source)
-- =============================================================
-- ЮУНЫ ТӨЛӨӨ:
-- MGL-ийн өмнөх ~300 үнийн санал Excel дээр, апп-аас ГАДУУР хийгдсэн. Юүлүүр
-- (0168) утга учиртай болохын тулд тэдгээрийг системд буцаан бүртгэх ёстой.
-- Ийм мөрүүд нь апп дотор загвараас үүссэн мөрүүдээс НЭГ ЧУХАЛ ЗҮЙЛЭЭР
-- ялгаатай: тэдэнд ажлын дэвтэр (`sheet_json`) БАЙХГҮЙ — зөвхөн хоосон
-- дэвтэр үүснэ.
--
-- ⚠️ ЭНЭ НЬ ЗӨВХӨН ШОШГО БИШ, ФУНКЦИОНАЛЬ ШААРДЛАГА:
--    `sheet_json` хоосон мөр дээр PDF/хэвлэх нь УТГАГҮЙ — хэвлэх хуудас
--    хоосон дэвтрийг зурж, хэрэглэгч хоосон A4 авна. Тиймээс UI нь
--    `source <> 'app'` мөрд «PDF татах» үйлдлийг НУУНА
--    (`QuoteListPage` → `canPrintQuote`). Энэ баганыг устгах юм уу
--    үл тоомсорловол тэр алдаа буцаж ирнэ.
--
-- Мөн юүлүүрийн тоо эргэлзээ төрүүлэхэд («яагаад гэнэт 300 санал нэмэгдэв?»)
-- гарал үүслээр нь ялгаж харуулах боломж өгнө.
--
-- ХЭВ МАЯГ: `qto_runs.source` (`'revit'` / `'ifc'`)-тэй яг ижил шийдэл — тэр нь
-- хуучин pipeline-ийн өгөгдлийг ТҮҮХ болгон уншуулах боломжийг өгсөн бөгөөд
-- энэ репод өөрийгөө нотолсон.
--
-- Утгууд:
--   'app'    — апп дотор загвараас үүссэн, бүрэн ажлын дэвтэртэй.
--              DEFAULT тул одоо байгаа БҮХ мөр автоматаар үүнд ангилагдана.
--   'manual' — «Хурдан нэмэх» формоор гараар бүртгэсэн (Excel дээр хийгдсэн
--              санал). Хоосон дэвтэр.
--   'import' — багцаар (XLSX) оруулсан. Хоосон дэвтэр.
--
-- ⚠️ `'import'` нь ХАРААХАН БИЧИГДЭХГҮЙ (багц импорт хойшлуулагдсан), гэвч
--    утгыг нь ОДООНООС зөвшөөрч байна — ингэснээр импорт хийхэд ДАХИН
--    migration нэмэх шаардлагагүй.
--
-- ⚠️ CHECK хязгаарлалт ТАВИАГҮЙ — 0168-ын `status`-тай ижил шалтгаан: SQLite
--    `ALTER TABLE … ADD COLUMN` дээр CHECK зөвшөөрдөггүй, хүснэгтийг rebuild
--    хийх (path B) нь энэ үнэ цэнэд тохирохгүй. Валидац нь
--    `routes/quotes.ts` → `QUOTE_SOURCES` дээр.
--
-- ТҮҮХ БИЧИГДЭХГҮЙ: `source` нь 'manual'/'import' мөрүүд `quote_status_history`
-- -д мөр үүсгэдэггүй (тэд `PATCH /:id/status`-аар дамждаггүй, статусаа шууд
-- авдаг). 300 хиймэл мөр жинхэнэ шилжилтүүдийг булах байсан; гарал үүслийг
-- энэ багана өөрөө тайлбарлана.
-- =============================================================

ALTER TABLE quotes ADD COLUMN source TEXT NOT NULL DEFAULT 'app';

-- Юүлүүрийн задаргаанд «эдгээрийн хэд нь буцаан бүртгэсэн бэ» гэж шүүхэд.
CREATE INDEX IF NOT EXISTS idx_quotes_source ON quotes(source);
