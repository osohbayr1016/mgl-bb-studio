-- =============================================================
-- Үнийн саналын статусын ТҮҮХ
-- =============================================================
-- `quotes.status` нь зөвхөн ОДООГИЙН байдлыг хадгална. Юүлүүрийн тоо
-- эргэлзээ төрүүлэхэд («яагаад өнгөрсөн сард 12 гэрээ байсан нь одоо 11
-- болов?») хэн, хэзээ, юунаас юу руу шилжүүлснийг харах хэрэгтэй болно.
-- Мөн 0168-аар нэмэгдсэн урсгал нь ӨНГӨРСӨН оны саналыг гараар буцаан
-- бүртгэх боломж өгдөг тул «энэ мөрийг хэн оруулав» гэдэг бүр ч чухал.
--
-- Мөр нь ЗӨВХӨН НЭМЭГДЭНЭ (append-only) — статус солигдох болгонд нэг мөр.
-- Анхны үүсэх (draft) үед мөр бичихгүй: `quotes.created_at` тэрийг хэлнэ.
--
-- `from_status` нь NULL байж болно — 0168-аас ӨМНӨ үүссэн, түүхгүй саналыг
-- анх удаа шилжүүлэхэд өмнөх утга нь `draft` гэсэн DEFAULT байсан эсэх нь
-- бодитоор мэдэгдэхгүй тохиолдол.
--
-- ⚠️ D1 нь тунхагласан FK-г ажиллах үедээ шахдаггүй ч `migrations apply` нь
--    транзакц дотор ажилладаг тул cascade ажиллана. `quotes` мөр устахад энэ
--    хүснэгтийн мөрүүд ХАМТ устна — тийм байх ёстой (устсан саналын түүх
--    хэрэггүй), гэхдээ `routes/quotes.ts`-ийн DELETE нь өөрөө гараар
--    цэвэрлэдэг (репогийн manual-delete конвенц).
-- =============================================================

CREATE TABLE IF NOT EXISTS quote_status_history (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  quote_id INTEGER NOT NULL REFERENCES quotes(id) ON DELETE CASCADE,
  from_status TEXT,
  to_status TEXT NOT NULL,
  -- Шилжүүлэх агшны дүнгийн зураг — дараа нь `quotes.contract_amount`
  -- засагдсан ч «тэр үед ямар дүнгээр гэрээ болсон» нь үлдэнэ.
  contract_amount REAL,
  note TEXT,
  changed_by_id INTEGER REFERENCES users(id),
  changed_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Нэг саналын түүхийг цаг хугацааны дарааллаар татах (дэлгэрэнгүй хуудас).
CREATE INDEX IF NOT EXISTS idx_quote_status_hist ON quote_status_history(quote_id, changed_at);
