-- Эзний шийдвэр (2026-09-08): захиалагчийн илгээсэн файлыг ажилтан
-- «Хүлээн авах» дармагц манай архивт АВТОМАТААР шургуулна.  Урьд нь
-- `POST /api/client-admin/submissions/:id/archive` гэсэн ГАРААР дардаг
-- товч байсан бөгөөд тэр товчинд UI ч байгаагүй тул хүлээн авсан
-- материал архивт огт хүрдэггүй байв.
--
-- ЯАГААД БАГАНА ХЭРЭГТЭЙ ВЭ?
--   2026-09-03-нд `documents` модуль `projects`-оос БҮРМӨСӨН САЛСАН
--   (0249-0251).  Тиймээс «энэ төслийн архив» гэсэн ойлголт систем дээр
--   БАЙХГҮЙ: продакшнд 22 архив, 31 төсөл байгаа ч хооронд нь холбох
--   ямар ч түлхүүр алга (архив `DOC-YYMMDD …`, төсөл `MGL-YYMMDD …`
--   гэж ӨӨР ӨӨР дугаарлагдсан).  Автоматжуулахын тулд «аль архивын аль
--   хавтас» гэдгийг ХААШАА НЭГ ГАЗАР бичих ёстой.
--
--   ⚠️ Энэ нь `seedProjectFolders`-ыг СЭРГЭЭХГҮЙ.  Эзэн «Projects дээрх
--      төслүүд Documents хуудсанд АВТОМАТААР дуудагдахыг болиул» гэсэн;
--      тэр бол төсөл бүрд 00-12 загварын хавтас ӨӨРӨӨ ҮҮСГЭХ тухай байв.
--      Энд эсрэгээрээ: админ өөрөө сонгосон нэг архив руу заана, сонгоогүй
--      бол юу ч болохгүй.  Автоматаар хавтас ч, архив ч ҮҮСГЭХГҮЙ.
--
-- ЯАГААД `ALTER TABLE ... ADD COLUMN` ВЭ?
--   `projects` бол CASCADE гинжний ЭЦЭГ (33 хүүхэд хүснэгт).  D1 дээр
--   `migrations apply` нь файлыг гүйлгээнд боодог тул parent-ыг дахин
--   барих нь бүх хүүхэд мөрийг УСТГАНА (CLAUDE.md-ийн path-B runbook).
--   Тиймээс ЗӨВХӨН багана нэмнэ — 0143 (`is_pending`), 0211 (`asr_only`),
--   0254 (`source_project_id`)-тэй ЯГ ижил хэв маяг.
--
-- ҮЙЛ АЖИЛЛАГААНЫ ҮР ДАГАВАР:
--   (a) D1 нь ажиллах үедээ FK-г ХЭРЭГЖҮҮЛДЭГГҮЙ тул энд бичсэн
--       `ON DELETE SET NULL` нь зөвхөн БАРИМТЖУУЛАЛТ.  Архив/хавтас
--       устгахад эдгээр багана ӨӨРӨӨ NULL болохгүй — тиймээс
--       `copySubmissionToArchive()` нь зорилтот архив амьд эсэхийг
--       (`deleted_at IS NULL`) хуулахын ӨМНӨ БҮРТ шалгана.  Устсан цэг
--       рүү заасан төсөл нь «тохируулаагүй»-тэй ижил замаар унана,
--       алдаа өгөхгүй.
--   (b) `folder_id` нь NULL байж БОЛНО — архивын үндэс рүү хуулна.
-- =============================================================

ALTER TABLE projects ADD COLUMN client_intake_archive_id INTEGER REFERENCES document_archives(id) ON DELETE SET NULL;

ALTER TABLE projects ADD COLUMN client_intake_folder_id INTEGER REFERENCES document_folders(id) ON DELETE SET NULL;
