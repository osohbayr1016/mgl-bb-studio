function colName(c) {
  let name = '';
  let n = c;
  do {
    name = String.fromCharCode(65 + (n % 26)) + name;
    n = Math.floor(n / 26) - 1;
  } while (n >= 0);
  return name;
}
const ref = (r, c) => `${colName(c)}${r + 1}`;

function makeSheet(id, name, cols) {
  const cells = {};
  const merges = [];
  let rows = 0;
  const put = (r, c, cell) => {
    cells[ref(r, c)] = cell;
    if (r + 1 > rows) rows = r + 1;
  };
  const span = (r, c1, c2, cell) => {
    if (c2 > c1) merges.push({ r, c: c1, rs: 1, cs: c2 - c1 + 1 });
    put(r, c1, cell);
  };
  const vspan = (r1, r2, c, cell) => {
    if (r2 > r1) merges.push({ r: r1, c, rs: r2 - r1 + 1, cs: 1 });
    put(r1, c, cell);
  };
  return {
    id,
    name,
    cols,
    put,
    span,
    vspan,
    build: () => ({ id, name, rows, cols, colWidths: undefined, merges, cells, anchors: {} }),
  };
}

